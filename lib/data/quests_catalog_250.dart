/// Rétrocompatibilité 250 quêtes
const List<QuestCatalogItem> kAllQuests250 = kAllQuests500;

/// Moteur d'auto-ajustement des quêtes en fonction de la date.
class QuestAutoAdjuster {
  /// Renvoie l'ensemble des 500 quêtes.
  static List<QuestCatalogItem> get allQuests => kAllQuests500;

  /// Quêtes journalières actives pour une date donnée (rotation quotidienne).
  static List<QuestCatalogItem> getDailyQuests(DateTime date, {int count = 6}) {
    final daily = kAllQuests500.where((q) => q.period == 'daily').toList();
    if (daily.isEmpty) return const [];
    final dayOfYear =
        int.parse('${date.year}${date.month.toString().padLeft(2, '0')}${date.day.toString().padLeft(2, '0')}');
    final selected = <QuestCatalogItem>[];
    for (var i = 0; i < count; i++) {
      final idx = (dayOfYear * 7 + i * 13) % daily.length;
      selected.add(daily[idx]);
    }
    return selected;
  }

  /// Quêtes mensuelles actives pour le mois en cours (ajustées au mois de l'année).
  static List<QuestCatalogItem> getMonthlyQuests(DateTime date, {int count = 8}) {
    final currentMonth = date.month;
    final monthSpecific = kAllQuests500.where((q) => q.period == 'monthly' && q.monthAffinity == currentMonth).toList();
    final general = kAllQuests500.where((q) => q.period == 'monthly' && q.monthAffinity == 0).toList();

    final result = [...monthSpecific, ...general];
    if (result.length <= count) return result;
    return result.take(count).toList();
  }

  /// Quêtes annuelles actives pour l'année universitaire courante.
  static List<QuestCatalogItem> getYearlyQuests(DateTime date, {int count = 12}) {
    final yearly = kAllQuests500.where((q) => q.period == 'yearly').toList();
    if (yearly.isEmpty) return const [];
    final yearSeed = date.year;
    final selected = <QuestCatalogItem>[];
    for (var i = 0; i < count && i < yearly.length; i++) {
      final idx = (yearSeed * 3 + i * 5) % yearly.length;
      selected.add(yearly[idx]);
    }
    return selected;
  }

  /// Quêtes auto-ajustées complètes (combiné journalier, mensuel et annuel).
  static List<QuestCatalogItem> getActiveQuests(DateTime date) {
    return [
      ...getDailyQuests(date),
      ...getMonthlyQuests(date),
      ...getYearlyQuests(date),
    ];
  }
}
