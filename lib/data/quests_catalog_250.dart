class QuestCatalogItem {
  final String id;
  final String title;
  final String description;
  final String period; // 'daily', 'monthly', 'yearly'
  final String category;
  final int targetValue;
  final int xpReward;
  final String iconName;
  final String colorHex;
  final int monthAffinity; // 0 = tout mois, 1-12 = affinité de mois
  final String criteriaType;

  const QuestCatalogItem({
    required this.id,
    required this.title,
    required this.description,
    required this.period,
    required this.category,
    required this.targetValue,
    required this.xpReward,
    required this.iconName,
    required this.colorHex,
    required this.monthAffinity,
    required this.criteriaType,
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'description': description,
        'period': period,
        'category': category,
        'targetValue': targetValue,
        'xpReward': xpReward,
        'iconName': iconName,
        'colorHex': colorHex,
        'monthAffinity': monthAffinity,
        'criteriaType': criteriaType,
      };
}

